// Generates src/icons/IconSet/glyphs/optical.ts: a per-glyph scale (about the centre 9,9) that brings each hand-drawn
// glyph's geometric size up toward the spec target (14.75 units on the larger side), at most +10%, and never past
// 15.75 units. Measured in Chromium with getBBox. Re-run after drawing or redrawing glyphs:
//   node --experimental-strip-types packages/oniva-ui/scripts/gen-icon-optical.mjs
import { register } from 'node:module';
import { writeFileSync } from 'node:fs';
register('./ts-resolve-hook.mjs', import.meta.url);

const TARGET = 14.75;
const MAX = 15.75;
const LIMIT = 1.1;

const { createElement } = await import('react');
const { renderToStaticMarkup } = await import('react-dom/server');
const out = new URL('../src/icons/IconSet/glyphs/optical.ts', import.meta.url);
// Measure raw drawings: write an empty table first so createIcon applies no scale while we measure.
writeFileSync(out, 'export const OPTICAL: Readonly<Record<string, number>> = {};\n');
const m = await import(new URL('../src/icons/IconSet/glyphs/index.ts', import.meta.url).href);
const variants = new Set(Object.keys(await import(new URL('../src/icons/IconSet/glyphs/variants.ts', import.meta.url).href)));
const glyphs = Object.entries(m).filter(([k, g]) => k.endsWith('Icon') && typeof g.parts === 'function' && !variants.has(k));
const svgs = glyphs.map(([, G]) => renderToStaticMarkup(createElement(G, { size: 18, optical: 'regular' })));

const { chromium } = await import('playwright');
const browser = await chromium.launch();
const page = await browser.newPage();
const dims = await page.evaluate((svgs) => {
  const host = document.createElement('div');
  document.body.appendChild(host);
  return svgs.map((s) => {
    host.innerHTML = s;
    let x0 = 99, y0 = 99, x1 = -99, y1 = -99;
    for (const e of host.querySelectorAll('path')) {
      if (e.closest('mask,clipPath,defs')) continue;
      const b = e.getBBox();
      x0 = Math.min(x0, b.x); y0 = Math.min(y0, b.y); x1 = Math.max(x1, b.x + b.width); y1 = Math.max(y1, b.y + b.height);
    }
    // farthest extent from the centre, so scaling about 9,9 never leaves the canvas
    return { size: Math.max(x1 - x0, y1 - y0), reach: Math.max(9 - x0, x1 - 9, 9 - y0, y1 - 9) };
  });
}, svgs);
await browser.close();

const entries = [];
glyphs.forEach(([name], i) => {
  const { size, reach } = dims[i];
  const k = Math.min(LIMIT, TARGET / size, MAX / 2 / reach);
  if (k > 1.005) entries.push(`  ${name.replace(/Icon$/, '')}: ${Math.round(k * 1000) / 1000},`);
});
writeFileSync(
  out,
  `// AUTO-GENERATED by scripts/gen-icon-optical.mjs — do not edit. Per-glyph optical scale about 9,9.\nexport const OPTICAL: Readonly<Record<string, number>> = {\n${entries.join('\n')}\n};\n`,
);
console.log(`gen-icon-optical: ${entries.length} of ${glyphs.length} glyphs scaled`);
