// Generates src/icons/IconSet/glyphs/variants.ts: every base glyph in BASES combined with every modifier mark in
// modifiers.ts, as `<Base><Modifier>Icon`. Hand-drawn glyphs with the same name win (they are skipped here).
// Run: node packages/oniva-ui/scripts/gen-icon-variants.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = join(dirname(fileURLToPath(import.meta.url)), '../src/icons/IconSet/glyphs');
const OUT = 'variants.ts';

// Bases whose meaning does not live in the bottom-right corner (the modifier erases that corner).
// FULL bases are interface objects that take every modifier; LIGHT bases are everyday subjects that only take the
// marks that make sense for any object (add, remove, favourite, find, status).
const words = (s) => s.split(/\s+/).filter(Boolean);
const FULL = words(`File FileText Folder FolderOpen Mail MailOpen Calendar CalendarDays User UserRound Users Database
Server Cloud Shield Bell Bookmark Image Images Video Film MessageSquare MessageCircle Messages Phone Home Building Globe
Map MapPin Settings Inbox Archive Package Box ShoppingCart ShoppingBag CreditCard Wallet Receipt Tag Ticket Clipboard
Notebook Book Key Link Code Terminal Cpu Monitor Laptop Smartphone Tablet Printer PhotoCamera Mic Headphones MusicNote
Layers LayoutGrid Table List Kanban Columns Rows Square Circle Briefcase Store Truck Bot Brain Wrench Plug Battery Wifi
Router Network Workflow Webhook Branch Container IdCard AlarmClock Timer PieChart BarChart LineChart Presentation Palette
Eye Filter Sliders Shapes Frame Pin Sparkles Rocket Keyboard Speaker Tv Cast Disc Fingerprint Vault Contact Cube Puzzle`);
const LIGHT = words(`Star Heart Gift Trophy Award Flag Coins Banknote PiggyBank Car Plane Bus Lightbulb Gamepad Hourglass Brush
PenTool Command Hash Zap Flask Atom GraduationCap Backpack School Tree Leaf Sun Moon Umbrella Coffee Utensils Dumbbell
Dice Ruler Scissors Crop Magnet Microscope Stethoscope Pill Syringe Activity Gauge Target Radar Satellite Anchor Compass
Tent Mountain Bed Sofa Lamp Door Window Crown Gem Medal Rosette Feather Paw Bird Fish Bug Siren Mouse Watch Signal Radio
Flame Droplet Snowflake Wind Waves Shirt Glasses Handbag Hospital Basket Basket Buildings BookOpen`);
const BASES = [...FULL, ...LIGHT];

const MODS = ['Plus', 'Minus', 'X', 'Check', 'Alert', 'Info', 'Clock', 'Lock', 'Star', 'Heart', 'Search', 'Settings',
  'Up', 'Down', 'Arrow', 'Sync', 'Play', 'Pause', 'Edit', 'Bolt', 'Share', 'Dot'];
const LIGHT_MODS = ['Plus', 'Minus', 'X', 'Check', 'Alert', 'Star', 'Heart', 'Search', 'Dot'];
const modsFor = (base) => (FULL.includes(base) ? MODS : LIGHT_MODS);

// name -> file for every hand-drawn glyph
const owner = new Map();
for (const f of readdirSync(dir)) {
  if (!f.endsWith('.ts') || f === OUT || f === 'index.ts') continue;
  for (const m of readFileSync(join(dir, f), 'utf8').matchAll(/export const ([A-Za-z0-9]+)Icon\b/g)) owner.set(m[1], f.replace(/\.ts$/, ''));
}

const imports = new Map(); // file -> Set(base)
const lines = [];
const missing = [];
const seen = new Set();
for (const base of [...new Set(BASES)]) {
  if (!owner.has(base)) { missing.push(base); continue; }
  for (const mod of modsFor(base)) {
    if (base.includes(mod)) continue; // e.g. no StarStar, LockLock
    const name = `${base}${mod}`;
    if (owner.has(name) || seen.has(name)) continue; // hand-drawn version wins
    seen.add(name);
    (imports.get(owner.get(base)) ?? imports.set(owner.get(base), new Set()).get(owner.get(base))).add(base);
    lines.push(`export const ${name}Icon = /*#__PURE__*/ m('${name}', ${base}Icon, '${mod}');`);
  }
}

const head = [
  '// AUTO-GENERATED by scripts/gen-icon-variants.mjs — do not edit. Base glyph + modifier mark (see modifiers.ts).',
  "import { withModifier as m } from '../modifiers';",
  ...[...imports].sort(([a], [b]) => a.localeCompare(b)).map(([f, s]) => `import { ${[...s].sort().map((b) => `${b}Icon`).join(', ')} } from './${f}';`),
  '',
];
writeFileSync(join(dir, OUT), head.concat(lines).join('\n') + '\n');
console.log(`gen-icon-variants: ${lines.length} variants from ${imports.size ? [...imports.values()].reduce((n, s) => n + s.size, 0) : 0} bases` + (missing.length ? `; missing bases: ${missing.join(' ')}` : ''));
